def _run(coro):
    async def wrapper():
        try:
            return await coro
        finally:
            # asyncpg connections are loop-bound; never leak them into the next test's loop
            await engine.dispose()

    return asyncio.run(wrapper())


def _sync_url(url: str) -> str:
    return url.replace("+asyncpg", "+psycopg")


@pytest.fixture(autouse=True)
def _quiesce_pool():
    """Alembic DDL needs no competing asyncpg connections (ACCESS EXCLUSIVE locks)."""
    _run(asyncio.sleep(0))
    yield
    _run(asyncio.sleep(0))


def test_revision_ids_fit_alembic_version_column():
    ids = []
    for path in sorted(VERSIONS_DIR.glob("*.py")):
        match = re.search(r'^revision = "([^"]+)"', path.read_text(encoding="utf-8"), re.M)
        assert match, f"{path.name} has no revision id"
        ids.append(match.group(1))
    too_long = [r for r in ids if len(r) > 32]
    assert not too_long, f"alembic_version.version_num is VARCHAR(32): {too_long}"
    assert len(ids) == len(set(ids))


def test_single_linear_head():
    script = ScriptDirectory.from_config(migrations.alembic_config())
    assert len(script.get_heads()) == 1
    assert migrations.head_revision() == script.get_current_head()


def test_database_is_at_head_and_models_have_no_drift():
    async def _status():
        async with engine.connect() as conn:
            return await migrations.schema_status(conn)

    status = _run(_status())
    assert status.at_head, status.as_dict()
    # Raises AutogenerateDiffsDetected when the models and the database differ.
    command.check(migrations.alembic_config())


def _check_models_against_db() -> None:
    """``alembic check`` without the "database is at head" precondition."""
    from alembic.autogenerate import compare_metadata
    from alembic.runtime.migration import MigrationContext

    sync = create_engine(_sync_url(os.environ["DATABASE_URL"]))
    try:
        with sync.connect() as conn:
            ctx = MigrationContext.configure(conn, opts={"compare_type": True})
            diffs = compare_metadata(ctx, metadata)
    finally:
        sync.dispose()
    if diffs:
        raise AutogenerateDiffsDetected(f"{len(diffs)} schema differences", None, diffs)  # type: ignore[arg-type]


def test_downgrade_one_step_then_upgrade_restores_head():
    cfg = migrations.alembic_config()
    head = migrations.head_revision()
    script = ScriptDirectory.from_config(cfg)
    previous = script.get_revision(head).down_revision
    assert isinstance(previous, str)

    command.downgrade(cfg, "-1")
    try:
        async def _current():
            async with engine.connect() as conn:
                return await migrations.current_revision(conn)

        assert _run(_current()) == previous
        # The head revision must change *something*, otherwise it is not capturing drift.
        with pytest.raises(AutogenerateDiffsDetected):
            _check_models_against_db()
    finally:
        command.upgrade(cfg, "head")
    command.check(cfg)


def test_face_encoding_company_backfill_through_revision_0007():
    """Downgrade below 0007 (drops face_encoding.companyId), upgrade again → companyId backfilled."""
    cfg = migrations.alembic_config()
    tag = uuid.uuid4().hex[:6]
    company = Company(
        companyId=uuid.uuid4(), companyName=f"bf-{tag}", companyCode=f"BF{tag}", companyInfo="bf", address="n/a"
    )
    dept = Department(departmentId=uuid.uuid4(), thName="d", engName="d", companyId=company.companyId)
    pos = Position(positionId=uuid.uuid4(), thName="p", engName="p", companyId=company.companyId)
    member = Member(
        memberId=uuid.uuid4(),
        username=f"bf-{tag}",
        email=f"bf-{tag}@example.com",
        passwordHash="!",
        role=RoleType.MEMBER,
        status=StatusType.ENABLE,
    )
    employee = CompanyEmployee(
        memberId=member.memberId,
        companyId=company.companyId,
        departmentId=dept.departmentId,
        positionId=pos.positionId,
    )
    encoding = FaceEncoding(
        faceEncodingId=uuid.uuid4(),
        memberId=member.memberId,
        companyId=None,
        embedding=[0.0] * FACE_EMBEDDING_DIM,
    )

    async def _seed():
        async with async_session() as db:
            db.add(company)
            await db.flush()
            db.add_all([dept, pos, member])
            await db.flush()
            db.add(employee)
            await db.flush()
            db.add(encoding)
            await db.commit()

    async def _company_of_encoding():
        async with async_session() as db:
            return (await db.get(FaceEncoding, encoding.faceEncodingId)).companyId

    async def _cleanup():
        async with async_session() as db:
            await db.execute(text('DELETE FROM face_encoding WHERE "memberId" = :m'), {"m": member.memberId})
            await db.execute(text('DELETE FROM company_employee WHERE "companyId" = :c'), {"c": company.companyId})
            for tbl in ("department", "position"):
                await db.execute(text(f'DELETE FROM {tbl} WHERE "companyId" = :c'), {"c": company.companyId})
            await db.execute(text('DELETE FROM member WHERE "memberId" = :m'), {"m": member.memberId})
            await db.execute(text('DELETE FROM company WHERE "companyId" = :c'), {"c": company.companyId})
            await db.commit()

    _run(_seed())
    try:
        command.downgrade(cfg, "0006_sentinel_vision_core")
        command.upgrade(cfg, "head")
        assert _run(_company_of_encoding()) == company.companyId
        command.check(cfg)
    finally:
        command.upgrade(cfg, "head")
        _run(_cleanup())


def test_legacy_create_all_database_can_be_stamped_and_upgraded():
    """Simulate a pre-B1 database (tables from create_all) → stamp 0008 → upgrade head → no drift."""
    base_url = os.environ["DATABASE_URL"]
    admin = create_engine(_sync_url(base_url), isolation_level="AUTOCOMMIT")
    legacy_db = f"dpu_legacy_{uuid.uuid4().hex[:8]}"
    try:
        with admin.connect() as conn:
            conn.execute(text(f'CREATE DATABASE "{legacy_db}"'))
    except Exception as exc:  # pragma: no cover - needs CREATEDB privilege
        pytest.skip(f"cannot create a scratch database: {exc}")

    legacy_url = re.sub(r"/[^/?]+(\?|$)", f"/{legacy_db}\\1", base_url, count=1)
    legacy_engine = create_engine(_sync_url(legacy_url))
    try:
        with legacy_engine.begin() as conn:
            conn.execute(text("CREATE EXTENSION IF NOT EXISTS vector"))
            Base.metadata.create_all(conn)
            # Columns the old startup DDL bolted on as nullable (models say NOT NULL).
            conn.execute(text("ALTER TABLE member ALTER COLUMN must_change_password DROP NOT NULL"))
            conn.execute(text("ALTER TABLE employee_timestamp ALTER COLUMN is_late DROP NOT NULL"))
            conn.execute(text("DROP INDEX IF EXISTS face_encoding_embedding_hnsw_idx"))
            conn.execute(text("DROP INDEX IF EXISTS uq_company_employee_code"))
        legacy_engine.dispose()

        saved = os.environ["DATABASE_URL"]
        os.environ["DATABASE_URL"] = legacy_url
        try:
            cfg = migrations.alembic_config()
            # Without the stamp, 0001 tries to create tables that already exist (and rolls back).
            with pytest.raises(Exception):
                command.upgrade(cfg, "head")
            command.stamp(cfg, LEGACY_STAMP)
            command.upgrade(cfg, "head")
            command.check(cfg)
        finally:
            os.environ["DATABASE_URL"] = saved
    finally:
        legacy_engine.dispose()
        with admin.connect() as conn:
            conn.execute(
                text("SELECT pg_terminate_backend(pid) FROM pg_stat_activity WHERE datname = :d"), {"d": legacy_db}
            )
            conn.execute(text(f'DROP DATABASE IF EXISTS "{legacy_db}"'))
        admin.dispose()
